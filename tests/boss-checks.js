import { enemies, player, runtime, corpses, inventory, INVENTORY_SIZE, questProgress, activeIgnites } from "../src/core/state.js";
import { resetAdventure, setGameState } from "../src/core/lifecycle.js";
import { updateBoss, resetBoss, BOSS_RULES } from "../src/combat/boss.js";
import { damageEnemy, updateEnemyRespawns } from "../src/combat/enemies.js";
import { damagePlayer } from "../src/player/player.js";
import { mapCollision } from "../src/world/collision.js";
import { collides } from "../src/world/movement.js";
import { setMenuOpen } from "../src/core/pause-menu.js";
import { enterArea } from "../src/world/areas.js";
import { createSave, parseSave, applySave } from "../src/persistence/saves.js";
import { lootCorpse } from "../src/loot/loot.js";
import { bossImage, drawBossSprite } from "../src/rendering/boss-sprites.js";
import { render } from "../src/rendering/renderer.js";
import { canvas } from "../src/rendering/canvas.js";
import { targetEnemyAtScreenPosition } from "../src/combat/targeting.js";

export function runBossChecks(assert) {
  resetAdventure("cave-arena");
  let boss = enemies.find(enemy=>enemy.isBoss);
  const position = (distance=50) => Object.assign(player,{x:boss.x+boss.w/2+distance-player.w/2,y:boss.y+boss.h/2-player.h/2,hp:100});
  const begin = (distance=50) => { resetBoss(boss); position(distance); boss.bossCooldown=0; updateBoss(boss,0); };
  try {
    assert(boss?.id === "00004" && !collides(boss.x,boss.y,boss), "Boss has stable ID and clear arena spawn");
    assert(questProgress.stonehorn.status === "active", "Entering arena starts boss quest");
    assert(bossImage.complete && bossImage.naturalWidth === 1536 && drawBossSprite(boss), "Boss renders from supplied sprite sheet");
    updateBoss(boss,1);
    assert(boss.bossState === "idle" && boss.hp === 600 && player.hp === 100, "Safe entry corridor does not start encounter");
    begin();
    render();
    const bounds=canvas.getBoundingClientRect();
    targetEnemyAtScreenPosition(bounds.left+(boss.x+boss.w/2-Math.floor(runtime.cameraX))*bounds.width/runtime.viewWidth,
      bounds.top+(boss.y-60-Math.floor(runtime.cameraY))*bounds.height/runtime.viewHeight);
    assert(runtime.selectedEnemy === boss, "Clicking boss body above its footprint selects it");
    assert(boss.bossAction.type === "cleave" && player.hp === 100, "Close boss attack has visible windup before damage");
    render();
    updateBoss(boss,0.4);
    assert(player.hp === 100, "Cleave gives time to react");
    player.x += 180; updateBoss(boss,0.6);
    assert(player.hp === 100 && !boss.bossAction, "Leaving cleave circle avoids damage");
    begin(); updateBoss(boss,1);
    assert(player.hp === 86 && !boss.bossAction, "Cleave hits once after windup");
    begin(); const warning = boss.bossAction.remaining;
    setMenuOpen(true); updateBoss(boss,1);
    assert(boss.bossAction.remaining === warning, "Pause freezes boss warning and damage");
    setMenuOpen(false); boss.stunRemaining=1; updateBoss(boss,0.5);
    assert(boss.bossAction.remaining === warning && player.hp === 100, "Stun freezes boss attack windup");
    begin(240);
    assert(boss.bossAction.type === "charge" && boss.bossAction.duration === BOSS_RULES.chargeWindup, "Distant boss attack signals an aimed charge");
    const aimY = boss.bossAction.ty;
    player.y += 180; updateBoss(boss,1.3); updateBoss(boss,1);
    assert(player.hp === 100 && !boss.bossAction && Math.abs(boss.y+boss.h/2-aimY)<1, "Charge uses locked direction and can be dodged");
    begin(240); updateBoss(boss,1.3); updateBoss(boss,1);
    assert(player.hp === 79, "Charge damages the player once while passing through");
    updateBoss(boss,0.01);
    assert(player.hp === 79, "Charge cannot repeatedly damage on contact");
    begin(240);
    const left=boss.x+100,top=boss.y-100;
    mapCollision.solid.push({left,top,right:left+10,bottom:top+200,points:[[left,top],[left+10,top],[left+10,top+200],[left,top+200]]});
    updateBoss(boss,1.3); updateBoss(boss,1);
    assert(!collides(boss.x,boss.y,boss) && boss.x+boss.w-3 <= left && player.hp === 100, "Boss charge stops at solid scenery");
    mapCollision.solid.pop();
    resetBoss(boss); boss.hp=200; position(); boss.bossCooldown=0; updateBoss(boss,0);
    assert(Math.abs(boss.bossAction.duration-0.675)<1e-9, "Boss enrages below half health with shorter warnings");
    activeIgnites.push({target:boss,remaining:10});
    player.y=1200;updateBoss(boss,0.1);
    assert(boss.hp === boss.maxHp && boss.bossState === "idle" && !boss.bossAction && activeIgnites.length === 0, "Retreat resets HP, attack, and attached damage effects");
    begin(); damagePlayer(1000);
    assert(runtime.gameState === "dead" && boss.bossState === "idle" && boss.hp === boss.maxHp && corpses.length === 0, "Player death resets unfinished boss encounter without rewards");
    player.hp=100; setGameState("playing");
    const goldBefore=player.gold;
    damageEnemy(boss,10000,"00001");
    assert(!boss.alive && questProgress.stonehorn.status === "completed" && player.gold === goldBefore+50, "Defeat completes boss quest and grants its reward");
    assert(corpses.length === 1 && corpses[0].enemyTypeId === "00004" && corpses[0].itemId === "02002" && corpses[0].gold === 3, "Boss corpse contains guaranteed Rare sword and gold");
    const rewarded=JSON.stringify([player.level,player.xp,player.gold,corpses.length]);
    damageEnemy(boss,10000,"00001");updateEnemyRespawns(1000);
    assert(JSON.stringify([player.level,player.xp,player.gold,corpses.length]) === rewarded && !boss.alive, "Repeated defeat and respawn updates cannot duplicate boss rewards");
    enterArea("cave");enterArea("cave-arena");
    boss=enemies.find(enemy=>enemy.isBoss);
    assert(!boss.alive && corpses.length === 1, "Defeated boss stays defeated on re-entry with unlooted corpse");
    const save=createSave(); applySave(JSON.stringify(save));
    boss=enemies.find(enemy=>enemy.isBoss);
    assert(!boss.alive && questProgress.stonehorn.status === "completed" && corpses[0].itemId === "02002", "Save/load preserves boss completion and remaining guaranteed loot");
    const corpse=corpses[0]; Object.assign(player,{x:corpse.x,y:corpse.y});
    inventory.items.splice(0,inventory.items.length,...Array(INVENTORY_SIZE).fill("00001"));
    lootCorpse(corpse);
    const goldAfter=player.gold;
    lootCorpse(corpse);
    assert(corpse.itemId === "02002" && player.gold === goldAfter && corpse.gold === 0, "Full inventory retains guaranteed item without granting gold twice");
    inventory.items.length=0;lootCorpse(corpse);
    assert(inventory.items.includes("02002") && corpses.length === 0, "Guaranteed boss item can be looted after freeing inventory space");
    applySave(JSON.stringify(createSave()));
    assert(!enemies.find(enemy=>enemy.isBoss).alive && corpses.length === 0, "Loading after looting cannot resurrect boss or recreate loot");
    const old=createSave();old.version=4;delete old.quests.stonehorn;
    const migrated=parseSave(JSON.stringify(old));
    assert(migrated.version === 5 && migrated.quests.stonehorn.status === "active", "Version 4 arena save migrates boss quest safely");
    const invalid=createSave();delete invalid.quests.stonehorn;
    let rejected=false;try{applySave(JSON.stringify(invalid));}catch{rejected=true;}
    assert(rejected && questProgress.stonehorn.status === "completed", "Current saves missing boss quest are rejected without mutating progress");
    resetAdventure("cave-arena");
    assert(enemies.find(enemy=>enemy.isBoss).alive && questProgress.stonehorn.status === "active", "Fresh adventure restores boss and starts a fresh encounter quest");
  } finally {
    setMenuOpen(false); setGameState("playing"); resetAdventure();
  }
}
