import { combatFeedback, player, enemies, runtime, keys, spellCooldowns } from "../src/core/state.js";
import { createSave, applySave } from "../src/persistence/saves.js";
import { damageEnemy, updateEnemies } from "../src/combat/enemies.js";
import { damagePlayer } from "../src/player/player.js";
import { equipItem } from "../src/player/inventory.js";
import { castFireball, swordAttack, chargeAttack, updateCharge, updateSpellCooldowns, resetSpellState, getActionUnavailableReason } from "../src/combat/spells.js";
import { SPELLS } from "../src/data/action-definitions.js";
import { getSpellStats } from "../src/player/stats.js";
import { updateCombatFeedback } from "../src/combat/feedback.js";
import { updateActionBarStatus } from "../src/ui/actionbar.js";
import { setMenuOpen } from "../src/core/pause-menu.js";
import { startGame } from "../src/core/lifecycle.js";
import { update } from "../src/core/update.js";
import { render } from "../src/rendering/renderer.js";
import { trees } from "../src/world/world-state.js";
import { buildings } from "../src/world/buildings.js";
import { mapCollision } from "../src/world/collision.js";

export function runCombatFeedbackChecks(assert) {
  const snapshot = JSON.stringify(createSave());
  const terrain = [mapCollision.walkable, mapCollision.floorHoles, mapCollision.solid, mapCollision.water, trees, buildings];
  const savedTerrain = terrain.map((list) => [...list]);
  const slot = (index) => document.querySelectorAll("#action-bar .action-slot")[index];
  try {
    terrain.forEach((list) => { list.length = 0; });
    enemies.forEach((enemy) => { enemy.alive = false; });
    const target = enemies[0];
    Object.assign(target, { alive: true, hp: 1000, maxHp: 1000, x: 900, y: 602, stunRemaining: 0 });
    player.x = 800; player.y = 600;
    runtime.selectedEnemy = target;
    resetSpellState();
    damageEnemy(target, 5, "00003");
    damageEnemy(target, 3.2, "00002");
    damagePlayer(7);
    assert(combatFeedback.numbers.map((entry) => entry.kind).join(",") === "direct,dot,incoming", "Floating numbers distinguish direct, DOT, and incoming damage");
    assert(combatFeedback.numbers[1].amount === 3.2 && new Set(combatFeedback.numbers.map((entry) => `${entry.x},${entry.y}`)).size === 3, "Fractional hits remain readable in separate lanes");
    assert(combatFeedback.flashes.length === 2, "Player and enemy both get a brief hit flash");
    render();
    const age = combatFeedback.numbers[0].age;
    setMenuOpen(true);
    updateCombatFeedback(5);
    assert(combatFeedback.numbers[0].age === age, "Pause freezes floating text and hit effects");
    setMenuOpen(false);
    updateCombatFeedback(0.15);
    assert(combatFeedback.flashes.length === 0 && combatFeedback.numbers.length === 3, "Hit flashes expire before damage numbers");
    updateCombatFeedback(1);
    assert(combatFeedback.numbers.length === 0, "Floating damage expires using delta time");
    for (let hit = 0; hit < 80; hit++) damageEnemy(target, 1, "00003");
    assert(combatFeedback.numbers.length === 5 && combatFeedback.numbers.reduce((sum, entry) => sum + entry.amount, 0) === 80, "Burst damage combines overflow into five readable lanes without losing totals");
    assert(new Set(combatFeedback.numbers.map((entry) => entry.lane)).size === 5, "Simultaneous damage lanes remain distinct");
    resetSpellState();
    equipItem("00001");
    trees.push({ x: 860, y: 614, trunkWidth: 10, trunkHeight: 30 });
    castFireball();
    assert(!player.casting && combatFeedback.notices.some((entry) => entry.text === "Blocked"), "Blocked casting shows an on-screen notice");
    updateActionBarStatus();
    assert(slot(0).dataset.unavailable === "blocked" && slot(0).getAttribute("aria-disabled") === "true", "Action bar reports blocked line of sight without spending resources");
    trees.length = 0;
    castFireball();
    keys.d = true;
    update(0.01);
    keys.d = false;
    assert(!player.casting && combatFeedback.notices.some((entry) => entry.kind === "interrupted"), "Moving interrupts casting with distinct visual feedback");
    resetSpellState();
    player.mana = 0;
    updateActionBarStatus();
    assert(slot(0).dataset.unavailable === "mana" && slot(0).querySelector(".action-status").textContent === "Mana", "Low mana dims action with a visible reason");
    castFireball();
    assert(combatFeedback.notices.some((entry) => entry.text === "Not enough mana"), "Failed mana check shows clear feedback");
    player.mana = 50;
    updateActionBarStatus();
    assert(!slot(0).dataset.unavailable, "Action becomes available when requirements recover");
    runtime.selectedEnemy = null;
    updateActionBarStatus();
    assert(slot(0).dataset.unavailable === "target", "Missing target is shown without logging messages each frame");
    runtime.selectedEnemy = target;
    equipItem("02000");
    updateActionBarStatus();
    assert(slot(0).dataset.unavailable === "weapon" && slot(2).dataset.unavailable === "range" && slot(3).dataset.unavailable === "too-close", "Weapon, range, and Charge minimum distance have separate indicators");
    target.x = player.x + 30; target.y = player.y + 2;
    updateActionBarStatus();
    assert(getActionUnavailableReason(getSpellStats(SPELLS["00003"])) === "" && !slot(2).dataset.unavailable, "Availability uses the same requirements as combat validation");
    swordAttack();
    updateActionBarStatus();
    assert(slot(2).querySelector(".action-cooldown").textContent === "0.6" && slot(2).dataset.unavailable === "cooldown", "Action slots display remaining cooldown immediately");
    setMenuOpen(true);
    update(5);
    updateActionBarStatus();
    assert(slot(2).querySelector(".action-cooldown").textContent === "0.6", "Pause freezes displayed cooldown time");
    setMenuOpen(false);
    updateSpellCooldowns(0.2);
    updateActionBarStatus();
    assert(slot(2).querySelector(".action-cooldown").textContent === "0.4", "Cooldown countdown follows gameplay delta time");
    updateSpellCooldowns(1);
    updateActionBarStatus();
    assert(slot(2).querySelector(".action-cooldown").textContent === "" && !slot(2).dataset.unavailable && slot(2).draggable, "Ready action clears countdown and retains drag controls");
    const observer = new MutationObserver(() => {});
    observer.observe(document.getElementById("action-bar"), { subtree: true, attributes: true, childList: true, characterData: true });
    updateActionBarStatus(); updateActionBarStatus();
    assert(observer.takeRecords().length === 0, "Unchanged action status avoids repeated DOM writes");
    observer.disconnect();
    resetSpellState();
    player.x = 800; player.y = 600;
    target.x = 1000; target.y = 602;
    chargeAttack();
    for (let step = 0; step < 20 && runtime.activeCharge; step++) updateCharge(0.05);
    assert(target.stunRemaining === 2, "Charge stun starts with its full duration");
    render();
    const stunnedX = target.x;
    updateEnemies(0.05);
    assert(target.x === stunnedX && target.stunRemaining === 1.95, "Stun visuals use the actual AI timer");
    setMenuOpen(true);
    update(2);
    assert(target.stunRemaining === 1.95, "Pausing freezes stun countdown");
    setMenuOpen(false);
    damageEnemy(target, 10000, "00003");
    updateActionBarStatus();
    assert(spellCooldowns["00004"] === 0 && slot(3).querySelector(".action-cooldown").textContent === "", "Enemy death immediately clears Charge cooldown display");
    const number = combatFeedback.numbers[combatFeedback.numbers.length - 1];
    assert(number.amount < 10000 && target.stunRemaining === 0, "Lethal damage reports actual health lost and clears stun");
    const save = JSON.stringify(createSave());
    assert(!save.includes("flashes") && !save.includes("notices"), "Visual combat effects are excluded from saves");
    applySave(save);
    assert(combatFeedback.numbers.length === 0 && combatFeedback.flashes.length === 0 && combatFeedback.notices.length === 0, "Loading clears combat feedback");
    damagePlayer(1);
    damagePlayer(10000);
    assert(combatFeedback.numbers.length === 0 && combatFeedback.flashes.length === 0 && combatFeedback.notices.length === 0, "Death clears floating feedback and flashes");
    startGame();
    updateActionBarStatus();
    assert(combatFeedback.time === 0 && [...document.querySelectorAll(".action-cooldown")].every((entry) => !entry.textContent), "Restart resets visual timers and cooldown labels");
  } finally {
    terrain.forEach((list, index) => list.splice(0, list.length, ...savedTerrain[index]));
    applySave(snapshot);
    updateActionBarStatus();
  }
}
