import { player, enemies, inventory, runtime, activeIgnites, fireballs, spellCooldowns, combatFeedback } from "../src/core/state.js";
import { resetAdventure } from "../src/core/lifecycle.js";
import { getPlayerStats, getSpellStats } from "../src/player/stats.js";
import { getItem } from "../src/data/items.js";
import { equipItem } from "../src/player/inventory.js";
import { rollPlayerHit } from "../src/combat/critical-hits.js";
import { castFireball, castIgnite, updateCasting, updateCombat, updateIgnites, swordAttack, rangedAttack, cancelCasting } from "../src/combat/spells.js";
import { mapCollision } from "../src/world/collision.js";
import { trees } from "../src/world/world-state.js";
import { buildings } from "../src/world/buildings.js";
import { SPELLS } from "../src/data/action-definitions.js";
import { createItemTooltip } from "../src/ui/inventory-ui.js";

export function runCriticalHitChecks(assert) {
  resetAdventure();
  const originalRandom = Math.random, staff = getItem("00001"), previousBonus = staff.stats.critChance;
  try {
    assert(getPlayerStats().critChance === 0.05, "Base critical chance is five percent");
    assert(rollPlayerHit(10, false, () => 0.049).damage === 20, "Roll below five percent doubles damage");
    assert(!rollPlayerHit(10, false, () => 0.05).critical, "Roll at five percent is a normal hit");
    assert(rollPlayerHit(10, true, () => 0.99).critical, "Guaranteed critical bypasses random roll");
    equipItem("00001");
    staff.stats.critChance = 0.1;
    assert(createItemTooltip(staff).includes("Critical chance: +10%"), "Item tooltip formats future critical bonuses as percentages");
    assert(Math.abs(getPlayerStats().critChance - 0.15) < 1e-9, "Equipment adds critical percentage points");
    staff.stats.critChance = 2;
    assert(getPlayerStats().critChance === 1, "Critical chance caps at one hundred percent");
    staff.stats.critChance = -2;
    assert(getPlayerStats().critChance === 0, "Critical chance cannot be negative");
    delete staff.stats.critChance;
    for (const list of Object.values(mapCollision)) list.length = 0;
    trees.length = 0; buildings.length = 0;
    Object.assign(player, { x: 800, y: 600, mana: 50 });
    const target = enemies[0];
    Object.assign(target, { x: 840, y: 600, hp: 1000, maxHp: 1000, alive: true });
    runtime.selectedEnemy = target;
    Math.random = () => 0.99;
    const base = getSpellStats(SPELLS["00001"]).damage;
    const launch = () => { updateCasting(0.36); updateCasting(0.12); };
    castIgnite();
    activeIgnites[0].remaining = 0.1;
    castFireball();
    updateIgnites(0.2);
    assert(activeIgnites.length === 0, "Burn expires during cast for guarantee test");
    launch();
    assert(fireballs[0].critical && fireballs[0].damage === base * 2, "Fireball cast on burning target retains guaranteed crit after burn expires");
    const hp = target.hp;
    updateCombat(0.2);
    assert(target.hp === Math.round((hp-base*2)*10)/10 && combatFeedback.numbers.some(n=>n.kind === "critical"), "Critical projectile deals double damage and emits critical feedback");
    player.mana = 50; spellCooldowns["00001"] = 0;
    castFireball(); launch();
    assert(!fireballs[0].critical && fireballs[0].damage === base, "Non-burning target uses normal critical chance");
    updateCombat(0.2);
    Math.random = () => 0;
    player.mana = 50; spellCooldowns["00001"] = 0;
    castFireball(); launch();
    assert(fireballs[0].critical, "Fireball can randomly crit without burning target");
    updateCombat(0.2);
    equipItem("02000");
    const beforeSword = target.hp, swordDamage = getSpellStats(SPELLS["00003"]).damage;
    swordAttack();
    assert(target.hp === Math.round((beforeSword-swordDamage*2)*10)/10, "Sword Strike uses shared critical-hit rules");
    inventory.items.push("01000"); equipItem("01000");
    rangedAttack();
    assert(fireballs[0]?.critical && fireballs[0].spellId === "00005", "Ranged attack rolls critical damage once when launched");
    fireballs.length = 0;
    equipItem("00001"); player.mana = 50; spellCooldowns["00002"] = 0;
    castIgnite();
    const beforeTick = target.hp, tickDamage = getSpellStats(SPELLS["00002"]).damagePerTick;
    updateIgnites(1);
    assert(target.hp === Math.round((beforeTick-tickDamage)*10)/10, "Ignite ticks do not gain direct-hit critical damage");
    spellCooldowns["00001"] = 0; castFireball(); cancelCasting();
    assert(!player.castGuaranteedCritical && fireballs.length === 0, "Canceled cast clears guaranteed crit without launching a projectile");
  } finally {
    Math.random = originalRandom;
    if (previousBonus === undefined) delete staff.stats.critChance;
    else staff.stats.critChance = previousBonus;
    resetAdventure();
  }
}
